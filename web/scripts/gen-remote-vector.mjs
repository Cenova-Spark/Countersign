// ─────────────────────────────────────────────────────────────────────────
//  Produce a countersignature with the browser signer, for Rust to check.
//
//  The relay path has two implementations of the same crypto — WebCrypto in a
//  phone, RustCrypto in the daemon — and they have to agree about the key, the
//  payload, the encoding and the low-S rule. Agreeing in prose is not evidence.
//  This writes a real signature out; `crates/signetd/src/relay.rs` reads it
//  back and runs it through the same acceptance path a live approval takes.
//
//    node scripts/gen-remote-vector.mjs
// ─────────────────────────────────────────────────────────────────────────
import { webcrypto } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

globalThis.crypto ??= webcrypto
globalThis.btoa ??= (s) => Buffer.from(s, 'binary').toString('base64')
globalThis.atob ??= (s) => Buffer.from(s, 'base64').toString('binary')

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

const { countersign, loadSignet, requestDigest, REMOTE_TEST_KEY_DERIVATION } = await import(
  join(root, 'src/lib/sign.js')
)
const { canonicalize } = await import(join(root, 'src/lib/jcs.js'))

// The wire spec's own example request (§2), so the fixture is anchored to
// something already in the repository rather than to something invented here.
const approval = JSON.parse(readFileSync(join(root, '../spec/vectors/approval.json'), 'utf8'))
const request = JSON.parse(approval.envelope.request_json)

const requestJson = canonicalize(request)
const digest = await requestDigest(request)
if (digest !== approval.envelope.bundle.request_digest) {
  throw new Error(`digest drifted: ${digest}`)
}

const signet = await loadSignet()
// A fixed counter and timestamp so the fixture is reproducible; the signature
// itself is not deterministic (ECDSA uses a fresh k), which is why the Rust
// side verifies it rather than comparing it byte for byte.
const counter = 7
const signature = await countersign({ requestDigest: digest, counter, dwellMs: 5120 })

writeFileSync(
  join(root, '../crates/signetd/tests/fixtures/remote-approval.json'),
  `${JSON.stringify(
    {
      NOTE:
        'GENERATED by web/scripts/gen-remote-vector.mjs. A countersignature produced ' +
        'by the browser signer, for the daemon to verify. Signed with a PUBLISHED test ' +
        'key; a default verifier refuses it.',
      derivation: REMOTE_TEST_KEY_DERIVATION,
      device_id: signet.deviceId,
      public_key_sec1_uncompressed_hex: signet.publicKeySec1Hex,
      request_json: requestJson,
      request_digest: digest,
      signature,
    },
    null,
    2,
  )}\n`,
)

console.log(`device_id ${signet.deviceId}`)
console.log(`signature ${signature.signature}`)
console.log('written to crates/signetd/tests/fixtures/remote-approval.json')
